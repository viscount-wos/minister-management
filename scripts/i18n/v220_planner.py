def put(tree, dotted, value):
    parts = dotted.split('.')
    node = tree
    for p in parts[:-1]:
        node = node.setdefault(p, {})
    node[parts[-1]] = value


def main():
    keys = list(EN)
    for lang in ('en', 'es', 'fr', 'de', 'pl', 'ko', 'zh', 'tr', 'ar'):
        vals = list(EN.values()) if lang == 'en' else TR[lang]
        assert len(vals) == len(keys), (lang, len(vals), len(keys))
        path = LOC / lang / 'svs.json'
        data = json.loads(path.read_text(encoding='utf-8'))
        data.pop('plan', None)
        data.pop('view', None)
        for k, v in zip(keys, vals):
            put(data, k, v)
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        cpath = LOC / lang / 'changelog.json'
        c = json.loads(cpath.read_text(encoding='utf-8'))
        out = {}
        for k, v in c.items():
            if k == 'v220d':
                continue
            out[k] = v
            if k == 'v220c':
                out['v220d'] = CHANGELOG[lang]
        if 'v220d' not in out:
            raise SystemExit('v220c missing in ' + lang)
        cpath.write_text(json.dumps(out, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('ok', len(keys), 'keys')


